
# Part A - List Warmup

# 1. Create a list containing four fruits
fruits = ["Apple", "Banana", "Mango", "Orange"]

# 2. Print the first and last items using indexes
print("First fruit:", fruits[0])
print("Last fruit:", fruits[-1])

# 3. Add a fifth fruit
fruits.append("Pineapple")
print("After adding a fruit:", fruits)

# 4. Remove one fruit
fruits.remove("Banana")
print("After removing a fruit:", fruits)

# 5. Count the remaining fruits
print("Number of fruits remaining:", len(fruits))
